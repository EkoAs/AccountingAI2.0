/**
 * Auto Balancer Module - Automatically generates offset transactions and arranges data
 * Uses AI to suggest balanced transaction pairs
 */

class AutoBalancer {
  constructor() {
    this.commonOffsets = {
      // Expense → Cash/Bank
      '5100': { offsetCode: '1000', offsetName: 'Cash', type: 'credit' }, // Salary → Cash
      '5200': { offsetCode: '1000', offsetName: 'Cash', type: 'credit' }, // Rent → Cash
      '5300': { offsetCode: '1000', offsetName: 'Cash', type: 'credit' }, // Utilities → Cash
      '5400': { offsetCode: '1000', offsetName: 'Cash', type: 'credit' }, // Supplies → Cash
      '5500': { offsetCode: '1800', offsetName: 'Equipment', type: 'credit' }, // Depreciation → Equipment
      '5600': { offsetCode: '1000', offsetName: 'Cash', type: 'credit' }, // Insurance → Cash
      '5700': { offsetCode: '1000', offsetName: 'Cash', type: 'credit' }, // Marketing → Cash
      '5800': { offsetCode: '2100', offsetName: 'Debt', type: 'credit' }, // Interest → Debt
      
      // Asset → Cash/Bank
      '1200': { offsetCode: '1000', offsetName: 'Cash', type: 'credit' }, // Inventory → Cash
      '1800': { offsetCode: '1000', offsetName: 'Cash', type: 'credit' }, // Equipment → Cash
      
      // Liability → Cash
      '2000': { offsetCode: '1000', offsetName: 'Cash', type: 'debit' }, // Payable → Cash (payment)
      '2100': { offsetCode: '1000', offsetName: 'Cash', type: 'debit' }, // Debt → Cash (payment)
    };
  }

  /**
   * Suggest offset transaction for a given transaction
   * @param {object} transaction - Original transaction
   * @param {array} chartOfAccounts - Chart of accounts
   * @returns {object} Suggested offset transaction
   */
  suggestOffsetTransaction(transaction, chartOfAccounts) {
    const accountCode = transaction.accountCode;
    const offsetInfo = this.commonOffsets[accountCode];

    if (!offsetInfo) {
      // Default: offset to Cash
      return {
        description: `Offset for ${transaction.description}`,
        amount: transaction.amount,
        quantity: transaction.quantity,
        date: transaction.date,
        totalAmount: transaction.totalAmount,
        account: 'Cash',
        accountCode: '1000',
        accountType: 'Asset',
        debitAmount: offsetInfo?.type === 'debit' ? transaction.totalAmount : 0,
        creditAmount: offsetInfo?.type === 'credit' ? transaction.totalAmount : 0,
        classification: 'Asset',
        aiConfidence: 0.7,
        reasoning: 'Auto-generated offset transaction to balance entry',
        isAutoGenerated: true
      };
    }

    // Find offset account in chart
    let offsetAccount = chartOfAccounts.find(a => a.code === offsetInfo.offsetCode);
    if (!offsetAccount) {
      offsetAccount = { code: offsetInfo.offsetCode, name: offsetInfo.offsetName, type: 'Asset' };
    }

    const isDebit = offsetInfo.type === 'debit';

    return {
      description: `Offset for ${transaction.description}`,
      amount: transaction.amount,
      quantity: transaction.quantity,
      date: transaction.date,
      totalAmount: transaction.totalAmount,
      account: offsetAccount.name,
      accountCode: offsetAccount.code,
      accountType: offsetAccount.type,
      debitAmount: isDebit ? transaction.totalAmount : 0,
      creditAmount: !isDebit ? transaction.totalAmount : 0,
      classification: offsetAccount.type,
      aiConfidence: 0.85,
      reasoning: `Auto-generated offset: ${transaction.account} (${transaction.accountCode}) ↔ ${offsetAccount.name} (${offsetAccount.code})`,
      isAutoGenerated: true
    };
  }

  /**
   * Arrange transactions in proper accounting order
   * @param {array} transactions - All transactions
   * @param {array} chartOfAccounts - Chart of accounts
   * @returns {array} Arranged transactions
   */
  arrangeTransactions(transactions, chartOfAccounts) {
    // Create account priority map
    const accountPriority = {};
    chartOfAccounts.forEach((account, index) => {
      accountPriority[account.code] = {
        type: account.type,
        priority: this.getTypePriority(account.type),
        index: index
      };
    });

    // Sort transactions by:
    // 1. Date (chronological)
    // 2. Account type priority (Assets → Liabilities → Equity → Revenue → Expense)
    // 3. Account code
    const sorted = [...transactions].sort((a, b) => {
      // First by date
      const dateCompare = new Date(a.date) - new Date(b.date);
      if (dateCompare !== 0) return dateCompare;

      // Then by account type priority
      const aPriority = accountPriority[a.accountCode]?.priority || 999;
      const bPriority = accountPriority[b.accountCode]?.priority || 999;
      if (aPriority !== bPriority) return aPriority - bPriority;

      // Then by account code
      return a.accountCode.localeCompare(b.accountCode);
    });

    return sorted;
  }

  /**
   * Get priority for account type
   * @param {string} type - Account type
   * @returns {number} Priority (lower = higher priority)
   */
  getTypePriority(type) {
    const priorities = {
      'Asset': 1,
      'Liability': 2,
      'Equity': 3,
      'Revenue': 4,
      'Expense': 5
    };
    return priorities[type] || 999;
  }

  /**
   * Validate if transactions are balanced
   * @param {array} transactions - All transactions
   * @returns {object} Validation result
   */
  validateBalance(transactions) {
    let totalDebits = 0;
    let totalCredits = 0;

    transactions.forEach(txn => {
      totalDebits += txn.debitAmount || 0;
      totalCredits += txn.creditAmount || 0;
    });

    const discrepancy = Math.abs(totalDebits - totalCredits);
    const balanced = discrepancy < 0.01;

    return {
      balanced,
      totalDebits,
      totalCredits,
      discrepancy,
      message: balanced 
        ? '✅ Transactions are balanced'
        : `❌ Unbalanced by Rp ${discrepancy.toLocaleString('id-ID')}`
    };
  }

  /**
   * Generate AI prompt for transaction analysis
   * @param {array} transactions - All transactions
   * @param {array} chartOfAccounts - Chart of accounts
   * @returns {string} AI prompt
   */
  generateAnalysisPrompt(transactions, chartOfAccounts) {
    const validation = this.validateBalance(transactions);
    
    const transactionList = transactions.map(t => 
      `${t.date} | ${t.accountCode} ${t.account} | ${t.description} | D:${t.debitAmount} C:${t.creditAmount}`
    ).join('\n');

    return `Analyze these accounting transactions and suggest improvements:

TRANSACTIONS:
${transactionList}

BALANCE STATUS:
Total Debits: Rp ${validation.totalDebits.toLocaleString('id-ID')}
Total Credits: Rp ${validation.totalCredits.toLocaleString('id-ID')}
Status: ${validation.message}

AVAILABLE ACCOUNTS:
${chartOfAccounts.map(a => `${a.code}: ${a.name} (${a.type})`).join('\n')}

TASKS:
1. Identify unbalanced entries
2. Suggest offset transactions to balance
3. Recommend proper account arrangement
4. Provide corrected transaction list

Respond in JSON format:
{
  "analysis": "Brief analysis of current state",
  "unbalancedEntries": [
    {
      "date": "YYYY-MM-DD",
      "accountCode": "code",
      "description": "description",
      "issue": "why it's unbalanced",
      "suggestedOffset": {
        "accountCode": "offset account code",
        "accountName": "offset account name",
        "debitAmount": 0,
        "creditAmount": 0,
        "reasoning": "why this offset"
      }
    }
  ],
  "recommendations": [
    "recommendation 1",
    "recommendation 2"
  ],
  "correctedTransactions": [
    {
      "date": "YYYY-MM-DD",
      "accountCode": "code",
      "description": "description",
      "debit": 0,
      "credit": 0
    }
  ]
}`;
  }

  /**
   * Build transaction pairs (debit-credit pairs)
   * @param {array} transactions - All transactions
   * @returns {array} Transaction pairs
   */
  buildTransactionPairs(transactions) {
    const pairs = [];
    const processed = new Set();

    transactions.forEach((txn, index) => {
      if (processed.has(index)) return;

      // Find matching offset transaction
      const offsetIndex = transactions.findIndex((other, idx) => {
        if (idx <= index || processed.has(idx)) return false;
        
        // Match by date, amount, and opposite debit/credit
        const sameDate = txn.date === other.date;
        const sameAmount = Math.abs(
          (txn.debitAmount || 0) + (txn.creditAmount || 0) -
          (other.debitAmount || 0) - (other.creditAmount || 0)
        ) < 0.01;
        const opposite = 
          (txn.debitAmount > 0 && other.creditAmount > 0) ||
          (txn.creditAmount > 0 && other.debitAmount > 0);

        return sameDate && sameAmount && opposite;
      });

      if (offsetIndex !== -1) {
        pairs.push({
          debit: txn,
          credit: transactions[offsetIndex],
          balanced: true
        });
        processed.add(index);
        processed.add(offsetIndex);
      } else {
        pairs.push({
          debit: txn,
          credit: null,
          balanced: false
        });
        processed.add(index);
      }
    });

    return pairs;
  }
}

const autoBalancer = new AutoBalancer();
